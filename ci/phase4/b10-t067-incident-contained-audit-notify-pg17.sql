\set ON_ERROR_STOP on
-- T067 controlled security incident simulation ONLY on disposable CI PG17.
-- This synthetic relational drill complements (not substitutes for) the
-- independently verified REAL production team suspension+notification+audit
-- and the T066 RCA/guard red-green tests. NEVER execute on Supabase LIVE.
DO $guard$
BEGIN
 IF current_database() <> 'jb_b10_disposable' THEN
  RAISE EXCEPTION 'T067_REFUSE_NON_DISPOSABLE_DATABASE';
 END IF;
 IF to_regprocedure('private.current_owner_aal2()') IS NULL
 OR to_regprocedure('private.current_session_active()') IS NULL
 OR to_regclass('public.audit_logs') IS NULL
 OR to_regclass('auth.sessions') IS NULL
 THEN RAISE EXCEPTION 'T067_PREVIOUS_SECURITY_FIXTURES_MISSING';END IF;
END $guard$;
BEGIN;
SET LOCAL statement_timeout='20s';
-- Synthetic table is rollback-only; production has its own real durable table.
CREATE TABLE public.live_notifications(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 recipient_user_id uuid NOT NULL,notification_type text NOT NULL,
 priority text NOT NULL,safe_message text NOT NULL,record_id text NOT NULL
);
ALTER TABLE public.live_notifications ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.live_notifications FROM PUBLIC,anon,authenticated;

DO $incident$
DECLARE
 owner_id uuid:='11111111-1111-1111-1111-111111111111';
 reporter_a uuid:='22222222-2222-2222-2222-222222222222';
 reporter_b uuid:='44444444-4444-4444-8444-444444444444';
 reporter_b_session uuid:='40000000-0000-4000-8000-000000000065';
 owner_session uuid:='10000000-0000-4000-8000-000000000063';
 reporter_a_session uuid:='20000000-0000-4000-8000-000000000063';
 before_audit bigint;
 n bigint;
BEGIN
 -- PRE: unrelated Reporter A and target Reporter B have independent sessions.
 IF (SELECT count(*) FROM auth.sessions WHERE user_id=reporter_b AND id=reporter_b_session)<>1
 OR (SELECT count(*) FROM auth.sessions WHERE user_id=reporter_a AND id=reporter_a_session)<>1
 OR (SELECT status FROM public.team_accounts WHERE user_id=reporter_b)<>'active'
 THEN RAISE EXCEPTION 'T067_PRE_INCIDENT_FIXTURE_NOT_ACTIVE';END IF;
 PERFORM set_config('request.jwt.claims',
 jsonb_build_object('role','authenticated','sub',reporter_b,
  'session_id',reporter_b_session,'aal','aal1')::text,true);
 IF NOT private.current_session_active() OR private.current_app_role()<>'reporter'::public.app_role
 THEN RAISE EXCEPTION 'T067_TARGET_REPORTER_ACTIVE_BEFORE_INCIDENT_MISSING';END IF;
 -- Negative: forged owner app_metadata + fake AAL2 cannot suspend anyone.
 PERFORM set_config('request.jwt.claims',
 jsonb_build_object('role','authenticated','sub',reporter_b,
 'session_id',reporter_b_session,'aal','aal2',
 'app_metadata',jsonb_build_object('role','owner'))::text,true);
 IF private.current_owner_aal2() IS TRUE THEN RAISE EXCEPTION 'T067_REPORTER_FORGED_OWNER';END IF;
 PERFORM set_config('request.jwt.claims',
 jsonb_build_object('role','authenticated','sub',owner_id,
  'session_id',owner_session,'aal','aal2')::text,true);
 IF private.current_owner_aal2() IS DISTINCT FROM TRUE
 THEN RAISE EXCEPTION 'T067_REAL_OWNER_AAL2_ACTIVE_SESSION_REQUIRED';END IF;
 SELECT count(*) INTO before_audit FROM public.audit_logs
 WHERE action='t067_controlled_incident_contained';
 -- Emulate the existing production team suspension atomic data effects:
 -- target team flag, revoke ONLY target sessions, immutable audit and safe
 -- notification with same reference. No real production RPC is invoked.
 UPDATE public.team_accounts SET status='suspended' WHERE user_id=reporter_b AND status='active';
 GET DIAGNOSTICS n=ROW_COUNT;
 IF n<>1 THEN RAISE EXCEPTION 'T067_ONE_TARGET_CONTAINMENT_REQUIRED';END IF;
 DELETE FROM auth.sessions WHERE user_id=reporter_b;
 GET DIAGNOSTICS n=ROW_COUNT;
 IF n<>1 THEN RAISE EXCEPTION 'T067_ONE_TARGET_SESSION_REVOKE_REQUIRED';END IF;
 INSERT INTO public.audit_logs(actor_user_id,action,record_type,record_id,metadata)
 VALUES(owner_id,'t067_controlled_incident_contained','team_account',reporter_b::text,
 jsonb_build_object('before','active','after','suspended','reason_code','CONTROLLED_DISPOSABLE_CI','scope','target_only'));
 INSERT INTO public.live_notifications(recipient_user_id,notification_type,priority,safe_message,record_id)
 VALUES(reporter_b,'TEAM_ACCOUNT_SUSPENDED','CRITICAL',
  'Your newsroom access was suspended.',''||reporter_b::text);
 IF (SELECT count(*) FROM public.audit_logs
 WHERE action='t067_controlled_incident_contained')<>before_audit+1
 OR NOT EXISTS(SELECT 1 FROM public.audit_logs a JOIN public.live_notifications n
 ON a.record_id=n.record_id WHERE a.action='t067_controlled_incident_contained'
 AND a.actor_user_id=owner_id AND a.metadata->>'before'='active'
 AND a.metadata->>'after'='suspended' AND n.priority='CRITICAL')
 THEN RAISE EXCEPTION 'T067_AUDIT_NOTIFICATION_CAUSAL_CHAIN_MISSING';END IF;
 IF EXISTS(SELECT 1 FROM public.live_notifications
 WHERE safe_message~*'(secret|recovery.key|bearer|password|token|refresh_token)')
 THEN RAISE EXCEPTION 'T067_SENSITIVE_NOTIFICATION_LEAK';END IF;
 -- Confirm old Reporter B bearer now loses backend role and session.
 PERFORM set_config('request.jwt.claims',
 jsonb_build_object('role','authenticated','sub',reporter_b,
 'session_id',reporter_b_session,'aal','aal1')::text,true);
 IF private.current_session_active() IS TRUE OR private.current_app_role() IS NOT NULL
 THEN RAISE EXCEPTION 'T067_REVOKED_INCIDENT_ACCOUNT_STILL_AUTHORIZED';END IF;
 -- Confirm unrelated Reporter A and Owner session remain fully usable.
 PERFORM set_config('request.jwt.claims',
 jsonb_build_object('role','authenticated','sub',reporter_a,
 'session_id',reporter_a_session,'aal','aal1')::text,true);
 IF private.current_session_active() IS DISTINCT FROM TRUE
 OR private.current_app_role()<>'reporter'::public.app_role
 THEN RAISE EXCEPTION 'T067_OTHER_REPORTER_COLLATERAL_DAMAGE';END IF;
 PERFORM set_config('request.jwt.claims',
 jsonb_build_object('role','authenticated','sub',owner_id,
 'session_id',owner_session,'aal','aal2')::text,true);
 IF private.current_owner_aal2() IS DISTINCT FROM TRUE
 THEN RAISE EXCEPTION 'T067_OWNER_SESSION_COLLATERAL_DAMAGE';END IF;
END $incident$;
ROLLBACK;
\echo 'PASS T067 isolated incident: Owner AAL2, forged-role deny, scoped team/session containment, correlated audit+CRITICAL notification, sanitization, old-session denial, unaffected other roles, full ROLLBACK; no LIVE effects.'
