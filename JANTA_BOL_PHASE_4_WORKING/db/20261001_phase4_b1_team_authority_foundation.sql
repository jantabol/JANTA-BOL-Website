-- Applied live: phase4_b1_team_authority_foundation
-- JANTA BOL Phase 4 B1 — Team / Authority Extension
-- Preserve auth.users -> user_roles -> reporters -> Live.
-- team_accounts stores lifecycle metadata only; user_roles remains effective authorization.

alter table public.reporters
  add column if not exists public_name_enabled boolean not null default true,
  add column if not exists updated_at timestamptz not null default now();

create table if not exists public.team_accounts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid unique references auth.users(id) on delete restrict,
  reporter_id uuid unique references public.reporters(id) on delete restrict,
  display_name text not null check (char_length(btrim(display_name)) between 1 and 120),
  contact text,
  invite_email text,
  assigned_role public.app_role not null default 'reporter'::public.app_role
    check (assigned_role <> 'owner'::public.app_role),
  status text not null default 'pending'
    check (status in ('pending','active','suspended','departed')),
  invited_at timestamptz not null default now(),
  activated_at timestamptz,
  suspended_at timestamptz,
  departed_at timestamptz,
  last_reactivated_at timestamptz,
  status_reason text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists team_accounts_status_idx
  on public.team_accounts(status, updated_at desc);
create index if not exists team_accounts_role_idx
  on public.team_accounts(assigned_role, status);

create table if not exists public.team_account_history (
  id bigint generated by default as identity primary key,
  team_account_id uuid not null references public.team_accounts(id) on delete restrict,
  actor_user_id uuid references auth.users(id) on delete set null,
  action text not null check (char_length(action) between 1 and 100),
  old_status text,
  new_status text,
  old_role public.app_role,
  new_role public.app_role,
  reason text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists team_account_history_account_idx
  on public.team_account_history(team_account_id, created_at desc);

alter table public.team_accounts enable row level security;
alter table public.team_account_history enable row level security;

drop policy if exists team_accounts_owner_read on public.team_accounts;
create policy team_accounts_owner_read on public.team_accounts
for select to authenticated using (private.current_owner_aal2());

drop policy if exists team_accounts_self_read on public.team_accounts;
create policy team_accounts_self_read on public.team_accounts
for select to authenticated
using (user_id=(select auth.uid()) and private.current_session_active());

drop policy if exists team_history_owner_read on public.team_account_history;
create policy team_history_owner_read on public.team_account_history
for select to authenticated using (private.current_owner_aal2());

revoke all on table public.team_accounts from anon,authenticated;
revoke all on table public.team_account_history from anon,authenticated;
grant select on table public.team_accounts to authenticated;
grant select on table public.team_account_history to authenticated;

insert into public.team_accounts(
  user_id,reporter_id,display_name,contact,assigned_role,status,
  invited_at,activated_at,created_at,updated_at
)
select
  ur.user_id,r.id,
  coalesce(nullif(btrim(r.name),''),nullif(split_part(u.email,'@',1),''),'Team Member'),
  r.contact,ur.role,'active',
  coalesce(r.created_at,ur.created_at,now()),
  coalesce(ur.created_at,r.created_at,now()),
  coalesce(r.created_at,ur.created_at,now()),now()
from public.user_roles ur
join auth.users u on u.id=ur.user_id
left join public.reporters r on r.user_id=ur.user_id
where ur.role<>'owner'::public.app_role
on conflict(user_id) do nothing;

create or replace function private.current_app_role()
returns public.app_role language sql stable security definer
set search_path='public','private','auth','pg_temp'
as $$
  select ur.role
  from public.user_roles ur
  where ur.user_id=auth.uid()
    and (
      ur.role='owner'::public.app_role
      or exists(
        select 1 from public.team_accounts ta
        where ta.user_id=ur.user_id and ta.status='active'
      )
    )
  limit 1;
$$;

create or replace function private.jb_team_history_internal(
  p_team_account_id uuid,p_actor_user_id uuid,p_action text,
  p_old_status text,p_new_status text,p_old_role public.app_role,
  p_new_role public.app_role,p_reason text default null,
  p_metadata jsonb default '{}'::jsonb
)
returns bigint language plpgsql security definer set search_path=''
as $$
declare v_id bigint;
begin
  insert into public.team_account_history(
    team_account_id,actor_user_id,action,old_status,new_status,
    old_role,new_role,reason,metadata
  ) values(
    p_team_account_id,p_actor_user_id,left(btrim(p_action),100),
    p_old_status,p_new_status,p_old_role,p_new_role,
    nullif(left(btrim(coalesce(p_reason,'')),500),''),
    coalesce(p_metadata,'{}'::jsonb)
  ) returning id into v_id;
  return v_id;
end;
$$;

create or replace function public.jb_team_create_pending_internal(
  p_owner_user_id uuid,p_user_id uuid,p_display_name text,p_contact text,
  p_role public.app_role,p_invite_email text default null
)
returns jsonb language plpgsql security definer set search_path=''
as $$
declare
  v_account public.team_accounts%rowtype;
  v_name text:=left(btrim(coalesce(p_display_name,'')),120);
  v_contact text:=nullif(left(btrim(coalesce(p_contact,'')),240),'');
  v_email text:=nullif(lower(left(btrim(coalesce(p_invite_email,'')),320)),'');
begin
  if not exists(select 1 from public.user_roles where user_id=p_owner_user_id and role='owner'::public.app_role)
    then raise exception 'OWNER_REQUIRED'; end if;
  if v_name='' then raise exception 'DISPLAY_NAME_REQUIRED'; end if;
  if p_role is null or p_role='owner'::public.app_role then raise exception 'INVALID_TEAM_ROLE'; end if;
  if p_user_id is not null and exists(select 1 from public.team_accounts where user_id=p_user_id)
    then raise exception 'TEAM_USER_ALREADY_EXISTS'; end if;

  insert into public.team_accounts(
    user_id,display_name,contact,invite_email,assigned_role,status,created_by
  ) values(p_user_id,v_name,v_contact,v_email,p_role,'pending',p_owner_user_id)
  returning * into v_account;

  perform private.jb_team_history_internal(
    v_account.id,p_owner_user_id,'team_invited',null,'pending',null,p_role,null,
    jsonb_build_object('user_linked',p_user_id is not null)
  );
  insert into public.audit_logs(actor_user_id,action,record_type,record_id,metadata)
  values(p_owner_user_id,'team_invited','team_account',v_account.id::text,
         jsonb_build_object('assigned_role',p_role::text,'user_linked',p_user_id is not null));

  return jsonb_build_object(
    'id',v_account.id,'user_id',v_account.user_id,'status',v_account.status,
    'assigned_role',v_account.assigned_role,'display_name',v_account.display_name
  );
end;
$$;

create or replace function public.jb_team_activate_internal(
  p_owner_user_id uuid,p_team_account_id uuid
)
returns jsonb language plpgsql security definer set search_path=''
as $$
declare v public.team_accounts%rowtype; v_reporter_id uuid;
begin
  if not exists(select 1 from public.user_roles where user_id=p_owner_user_id and role='owner'::public.app_role)
    then raise exception 'OWNER_REQUIRED'; end if;
  select * into v from public.team_accounts where id=p_team_account_id for update;
  if not found then raise exception 'TEAM_ACCOUNT_NOT_FOUND'; end if;
  if v.status<>'pending' then raise exception 'TEAM_ACCOUNT_NOT_PENDING'; end if;
  if v.user_id is null then raise exception 'TEAM_AUTH_USER_REQUIRED'; end if;
  if v.assigned_role='owner'::public.app_role then raise exception 'OWNER_ROLE_RESERVED'; end if;

  insert into public.user_roles(user_id,role,created_at,updated_at)
  values(v.user_id,v.assigned_role,now(),now())
  on conflict(user_id) do update set role=excluded.role,updated_at=now();

  if v.assigned_role='reporter'::public.app_role then
    select id into v_reporter_id from public.reporters where user_id=v.user_id;
    if v_reporter_id is null then
      insert into public.reporters(
        user_id,name,contact,active,live_permission,public_name_enabled,created_at,updated_at
      ) values(v.user_id,v.display_name,v.contact,true,false,true,now(),now())
      returning id into v_reporter_id;
    else
      update public.reporters set active=true,updated_at=now() where id=v_reporter_id;
    end if;
  else
    v_reporter_id:=v.reporter_id;
    if v_reporter_id is not null then
      update public.reporters set active=false,updated_at=now() where id=v_reporter_id;
    end if;
  end if;

  update public.team_accounts
  set reporter_id=coalesce(v_reporter_id,reporter_id),status='active',
      activated_at=coalesce(activated_at,now()),suspended_at=null,
      status_reason=null,updated_at=now()
  where id=v.id returning * into v;

  perform private.jb_team_history_internal(
    v.id,p_owner_user_id,'team_activated','pending','active',
    v.assigned_role,v.assigned_role,null,'{}'::jsonb
  );
  insert into public.audit_logs(actor_user_id,action,record_type,record_id,metadata)
  values(p_owner_user_id,'team_activated','team_account',v.id::text,
         jsonb_build_object('assigned_role',v.assigned_role::text));
  insert into public.live_notifications(
    recipient_user_id,notification_type,priority,title,safe_message,record_type,record_id
  ) values(v.user_id,'TEAM_ACCOUNT_ACTIVATED','HIGH','JANTA BOL access activated',
           'Aapka newsroom account activate ho gaya hai.','team_account',v.id::text);
  return jsonb_build_object('id',v.id,'status',v.status,'assigned_role',v.assigned_role,'user_id',v.user_id);
end;
$$;

create or replace function public.jb_team_suspend_internal(
  p_owner_user_id uuid,p_team_account_id uuid,p_reason text
)
returns jsonb language plpgsql security definer set search_path=''
as $$
declare
  v public.team_accounts%rowtype;
  v_reason text:=nullif(left(btrim(coalesce(p_reason,'')),500),'');
  v_sessions int:=0;
begin
  if not exists(select 1 from public.user_roles where user_id=p_owner_user_id and role='owner'::public.app_role)
    then raise exception 'OWNER_REQUIRED'; end if;
  if v_reason is null then raise exception 'REASON_REQUIRED'; end if;
  select * into v from public.team_accounts where id=p_team_account_id for update;
  if not found then raise exception 'TEAM_ACCOUNT_NOT_FOUND'; end if;
  if v.status<>'active' then raise exception 'TEAM_ACCOUNT_NOT_ACTIVE'; end if;
  if v.user_id is null then raise exception 'TEAM_AUTH_USER_REQUIRED'; end if;

  if v.assigned_role='reporter'::public.app_role
     and exists(select 1 from public.user_roles where user_id=v.user_id and role='reporter'::public.app_role) then
    perform public.jb_live_suspend_reporter_internal(p_owner_user_id,v.user_id,v_reason);
    perform public.jb_live_revoke_reporter_capabilities_internal(p_owner_user_id,v.user_id,v_reason);
  else
    delete from auth.sessions where user_id=v.user_id;
    get diagnostics v_sessions=row_count;
  end if;
  delete from public.user_roles where user_id=v.user_id and role<>'owner'::public.app_role;
  update public.team_accounts
  set status='suspended',suspended_at=now(),status_reason=v_reason,updated_at=now()
  where id=v.id;
  perform private.jb_team_history_internal(
    v.id,p_owner_user_id,'team_suspended','active','suspended',
    v.assigned_role,v.assigned_role,v_reason,
    jsonb_build_object('non_reporter_sessions_revoked',v_sessions)
  );
  insert into public.audit_logs(actor_user_id,action,record_type,record_id,metadata)
  values(p_owner_user_id,'team_suspended','team_account',v.id::text,
         jsonb_build_object('reason',v_reason,'assigned_role',v.assigned_role::text));
  insert into public.live_notifications(
    recipient_user_id,notification_type,priority,title,safe_message,record_type,record_id
  ) values(v.user_id,'TEAM_ACCOUNT_SUSPENDED','CRITICAL','JANTA BOL access suspended',
           'Aapka newsroom access suspend kiya gaya hai.','team_account',v.id::text);
  return jsonb_build_object('id',v.id,'status','suspended','user_id',v.user_id);
end;
$$;

