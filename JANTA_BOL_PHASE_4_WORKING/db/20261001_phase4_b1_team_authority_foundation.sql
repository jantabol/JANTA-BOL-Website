create or replace function public.jb_team_list()
returns table(
  team_account_id uuid,user_id uuid,reporter_id uuid,display_name text,contact text,
  invite_email text,assigned_role text,status text,public_name_enabled boolean,
  reporter_active boolean,live_permission boolean,invited_at timestamptz,
  activated_at timestamptz,suspended_at timestamptz,departed_at timestamptz,updated_at timestamptz
)
language plpgsql security definer set search_path=''
as $$
begin
  if not private.current_owner_aal2() then raise exception 'OWNER_AAL2_REQUIRED'; end if;
  return query
  select ta.id,ta.user_id,ta.reporter_id,ta.display_name,ta.contact,ta.invite_email,
         ta.assigned_role::text,ta.status,coalesce(r.public_name_enabled,false),
         coalesce(r.active,false),coalesce(r.live_permission,false),
         ta.invited_at,ta.activated_at,ta.suspended_at,ta.departed_at,ta.updated_at
  from public.team_accounts ta left join public.reporters r on r.id=ta.reporter_id
  order by case ta.status when 'pending' then 0 when 'active' then 1 when 'suspended' then 2 else 3 end,
           ta.updated_at desc;
end;
$$;

