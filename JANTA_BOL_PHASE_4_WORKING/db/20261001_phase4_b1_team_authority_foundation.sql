create or replace function public.jb_team_list_sessions(p_team_account_id uuid)
returns table(session_id uuid,created_at timestamptz,updated_at timestamptz,
  refreshed_at timestamp,aal text,user_agent text,ip text)
language plpgsql security definer set search_path=''
as $$
declare v_user uuid;
begin
  if not private.current_owner_aal2() then raise exception 'OWNER_AAL2_REQUIRED'; end if;
  select user_id into v_user from public.team_accounts where id=p_team_account_id;
  if v_user is null then return; end if;
  return query
  select s.id,s.created_at,s.updated_at,s.refreshed_at,s.aal::text,s.user_agent,s.ip::text
  from auth.sessions s where s.user_id=v_user
  order by coalesce(s.refreshed_at,s.updated_at::timestamp) desc;
end;
$$;

