create or replace function public.jb_team_depart_internal(
  p_owner_user_id uuid,p_team_account_id uuid,p_reason text
)
returns jsonb language plpgsql security definer set search_path=''
as $$
declare v public.team_accounts%rowtype;
  v_reason text:=nullif(left(btrim(coalesce(p_reason,'')),500),'');
begin
  if not exists(select 1 from public.user_roles where user_id=p_owner_user_id and role='owner'::public.app_role)
