create or replace function public.jb_public_reporter_directory()
returns table(reporter_id uuid,display_name text)
language sql stable security definer set search_path=''
as $$
  select r.id,r.name
  from public.reporters r join public.team_accounts ta on ta.reporter_id=r.id
  where r.public_name_enabled=true and ta.status in('active','departed')
  order by lower(r.name),r.id;
$$;

