create or replace function public.jb_team_change_role_internal(
  p_owner_user_id uuid,p_team_account_id uuid,p_new_role public.app_role,
  p_reason text default 'ROLE_CHANGED'
)
returns jsonb language plpgsql security definer set search_path=''
as $$
declare
  v public.team_accounts%rowtype; v_old_role public.app_role;
  v_reason text:=left(btrim(coalesce(p_reason,'ROLE_CHANGED')),500);
  v_reporter_id uuid;
begin
  if not exists(select 1 from public.user_roles where user_id=p_owner_user_id and role='owner'::public.app_role)
    then raise exception 'OWNER_REQUIRED'; end if;
  if p_new_role is null or p_new_role='owner'::public.app_role then raise exception 'OWNER_ROLE_RESERVED'; end if;
  select * into v from public.team_accounts where id=p_team_account_id for update;
  if not found then raise exception 'TEAM_ACCOUNT_NOT_FOUND'; end if;
  if v.status='departed' then raise exception 'TEAM_ACCOUNT_DEPARTED'; end if;
  v_old_role:=v.assigned_role;
  if v_old_role=p_new_role then
    return jsonb_build_object('id',v.id,'status',v.status,'assigned_role',v.assigned_role,'changed',false);
  end if;

  if v.status='active' and v.user_id is not null then
    if v_old_role='reporter'::public.app_role then
      if exists(select 1 from public.user_roles where user_id=v.user_id and role='reporter'::public.app_role) then
        perform public.jb_live_suspend_reporter_internal(p_owner_user_id,v.user_id,'TEAM_ROLE_CHANGED');
        perform public.jb_live_revoke_reporter_capabilities_internal(p_owner_user_id,v.user_id,'TEAM_ROLE_CHANGED');
      end if;
    else
      delete from auth.sessions where user_id=v.user_id;
    end if;
    insert into public.user_roles(user_id,role,created_at,updated_at)
    values(v.user_id,p_new_role,now(),now())
    on conflict(user_id) do update set role=excluded.role,updated_at=now();

    if p_new_role='reporter'::public.app_role then
      select id into v_reporter_id from public.reporters where user_id=v.user_id;
      if v_reporter_id is null then
        insert into public.reporters(
          user_id,name,contact,active,live_permission,public_name_enabled,created_at,updated_at
        ) values(v.user_id,v.display_name,v.contact,true,false,true,now(),now())
        returning id into v_reporter_id;
      else
        update public.reporters set active=true,updated_at=now() where id=v_reporter_id;
      end if;
      update public.team_accounts set reporter_id=v_reporter_id where id=v.id;
    elsif v.reporter_id is not null then
      update public.reporters set active=false,updated_at=now() where id=v.reporter_id;
    end if;
  end if;

  update public.team_accounts set assigned_role=p_new_role,updated_at=now() where id=v.id;
  perform private.jb_team_history_internal(
    v.id,p_owner_user_id,'team_role_changed',v.status,v.status,
    v_old_role,p_new_role,v_reason,'{}'::jsonb
  );
  insert into public.audit_logs(actor_user_id,action,record_type,record_id,metadata)
  values(p_owner_user_id,'team_role_changed','team_account',v.id::text,
         jsonb_build_object('old_role',v_old_role::text,'new_role',p_new_role::text,'reason',v_reason));
  return jsonb_build_object('id',v.id,'status',v.status,'old_role',v_old_role,'assigned_role',p_new_role,'changed',true);
end;
$$;

