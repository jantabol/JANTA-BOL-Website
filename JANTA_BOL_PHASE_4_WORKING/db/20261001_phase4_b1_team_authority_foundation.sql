returns table(history_id bigint,action text,old_status text,new_status text,old_role text,
  new_role text,reason text,metadata jsonb,created_at timestamptz)
language plpgsql security definer set search_path=''
as $$
begin
  if not private.current_owner_aal2() then raise exception 'OWNER_AAL2_REQUIRED'; end if;
  return query
  select h.id,h.action,h.old_status,h.new_status,h.old_role::text,h.new_role::text,
         h.reason,h.metadata,h.created_at
  from public.team_account_history h
  where h.team_account_id=p_team_account_id
