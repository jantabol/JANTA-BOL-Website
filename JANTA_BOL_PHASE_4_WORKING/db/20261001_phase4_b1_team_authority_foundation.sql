create or replace function public.jb_team_revoke_session_internal(
  p_owner_user_id uuid,p_team_account_id uuid,p_session_id uuid,
  p_reason text default 'LOST_DEVICE'
)
returns boolean language plpgsql security definer set search_path=''
as $$
declare v_user uuid; v_count int:=0;
  v_reason text:=left(btrim(coalesce(p_reason,'LOST_DEVICE')),500);
begin
  if not exists(select 1 from public.user_roles where user_id=p_owner_user_id and role='owner'::public.app_role)
    then raise exception 'OWNER_REQUIRED'; end if;
  select user_id into v_user from public.team_accounts where id=p_team_account_id;
  if v_user is null then raise exception 'TEAM_AUTH_USER_REQUIRED'; end if;
  delete from auth.sessions where id=p_session_id and user_id=v_user;
  get diagnostics v_count=row_count;
  if v_count<>1 then raise exception 'TEAM_SESSION_NOT_FOUND'; end if;
  perform private.jb_team_history_internal(
    p_team_account_id,p_owner_user_id,'team_session_revoked',null,null,null,null,v_reason,
    jsonb_build_object('session_id',p_session_id)
  );
  insert into public.audit_logs(actor_user_id,action,record_type,record_id,metadata)
  values(p_owner_user_id,'team_session_revoked','team_account',p_team_account_id::text,
         jsonb_build_object('reason',v_reason,'session_id',p_session_id));
  return true;
end;
$$;

