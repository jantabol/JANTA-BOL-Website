create or replace function public.jb_b9_search(
 p_query text default null,p_id text default null,p_date_from date default null,p_date_to date default null,
 p_year int default null,p_month int default null,p_district text default null,
 p_location text default null,p_category text default null,p_term text default null,
 p_sort text default 'latest',p_cursor jsonb default null,p_limit int default 20
) returns jsonb
language plpgsql stable security definer set search_path=''
as $fn$
declare 
 q text:=nullif(btrim(coalesce(p_query,'')),'');
 fid text:=nullif(btrim(coalesce(p_id,'')),'');
 district_filter text:=nullif(btrim(coalesce(p_district,'')),'');
 location_filter text:=nullif(btrim(coalesce(p_location,'')),'');
 category_filter text:=nullif(btrim(coalesce(p_category,'')),'');
 term_filter text:=nullif(btrim(coalesce(p_term,'')),'');
 sort_mode text:=coalesce(p_sort,'latest');
 lim integer:=greatest(1,least(coalesce(p_limit,20),50));
 cursor_id uuid; cursor_at timestamptz; cursor_rank integer; 
 items jsonb; next_token jsonb;
begin
 if sort_mode not in ('latest','oldest','relevance') then raise exception 'B9_INVALID_SORT'; end if;
 if length(coalesce(q,''))>120 or length(coalesce(fid,''))>36
    or length(coalesce(district_filter,''))>100 or length(coalesce(location_filter,''))>120
    or length(coalesce(category_filter,''))>90 or length(coalesce(term_filter,''))>120
 then raise exception 'B9_FILTER_TOO_LONG'; end if;
 if p_year is not null and p_year not between 1900 and 2200 then raise exception 'B9_INVALID_YEAR'; end if;
 if p_month is not null and p_month not between 1 and 12 then raise exception 'B9_INVALID_MONTH'; end if;
 if p_date_from is not null and p_date_to is not null and p_date_from>p_date_to then raise exception 'B9_INVALID_DATE_RANGE'; end if;
 if p_cursor is not null then
   if jsonb_typeof(p_cursor)<>'object' or p_cursor->>'sort' is distinct from sort_mode
     or coalesce(p_cursor->>'id','') !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
     or coalesce(p_cursor->>'at','') !~ '^\d{4}-\d\d-\d\dT'
   then raise exception 'B9_INVALID_CURSOR'; end if;
   cursor_id:=(p_cursor->>'id')::uuid;
   cursor_at:=(p_cursor->>'at')::timestamptz;
   cursor_rank:=coalesce((p_cursor->>'rank')::integer,0);
 end if;
 with matching as (
 select a.id,a.title,a.excerpt,a.category,a.district,a.location,a.news_date,a.published_at,
        coalesce(a.published_at,a.created_at) as sort_at,
        case when q is null then 0
             when lower(a.title)=lower(q) then 0
             when a.title ilike ('%'||q||'%') then 1
             when coalesce(a.excerpt,'') ilike ('%'||q||'%') then 2
             else 3 end as rnk,
        (select coalesce(jsonb_agg(jsonb_build_object('kind',t.kind,'slug',t.slug,'label',t.label) order by t.kind,t.slug),'[]'::jsonb)
          from public.b9_article_terms at
          join public.b9_taxonomy_terms t on t.id=at.term_id where at.article_id=a.id) as terms
 from public.articles a
 where a.status='published' and a.deleted_at is null
   and (q is null or a.title ilike ('%'||q||'%') or coalesce(a.excerpt,'') ilike ('%'||q||'%')
        or a.body ilike ('%'||q||'%')
        or to_tsvector('simple',coalesce(a.title,'')||' '||coalesce(a.excerpt,'')||' '||coalesce(a.body,''))
           @@ plainto_tsquery('simple',q))
   and (fid is null or a.id::text=fid)
   and (p_date_from is null or coalesce(a.news_date,(a.published_at at time zone 'Asia/Kolkata')::date)>=p_date_from)
   and (p_date_to is null or coalesce(a.news_date,(a.published_at at time zone 'Asia/Kolkata')::date)<=p_date_to)
   and (p_year is null or extract(year from coalesce(a.news_date,(a.published_at at time zone 'Asia/Kolkata')::date))::int=p_year)
   and (p_month is null or extract(month from coalesce(a.news_date,(a.published_at at time zone 'Asia/Kolkata')::date))::int=p_month)
   and (district_filter is null or a.district ilike district_filter)
   and (location_filter is null or a.location ilike ('%'||location_filter||'%'))
   and (category_filter is null or a.category ilike category_filter)
   and (term_filter is null or exists(
      select 1 from public.b9_article_terms at join public.b9_taxonomy_terms t on t.id=at.term_id
      where at.article_id=a.id and (lower(t.slug)=lower(term_filter) or lower(t.label)=lower(term_filter))))
 ), sorted_page as (
   select * from matching m where
    p_cursor is null or
    (sort_mode='latest' and (m.sort_at,m.id)<(cursor_at,cursor_id)) or
    (sort_mode='oldest' and (m.sort_at,m.id)>(cursor_at,cursor_id)) or
    (sort_mode='relevance' and (m.rnk>cursor_rank or (m.rnk=cursor_rank and (m.sort_at,m.id)<(cursor_at,cursor_id))))
   order by
     case when sort_mode='relevance' then m.rnk end asc nulls last,
     case when sort_mode in ('latest','relevance') then m.sort_at end desc nulls last,
     case when sort_mode in ('latest','relevance') then m.id end desc nulls last,
     case when sort_mode='oldest' then m.sort_at end asc nulls last,
     case when sort_mode='oldest' then m.id end asc nulls last
   limit lim+1
 ), numbered as (
   select row_number() over() as n,* from sorted_page
 )
 select 
   coalesce((select jsonb_agg(jsonb_build_object(
       'id',n.id,'title',n.title,'excerpt',n.excerpt,'category',n.category,
       'district',n.district,'location',n.location,'news_date',n.news_date,
       'published_at',n.published_at,'terms',n.terms,
       'permanent_url','article.html?id='||n.id::text) order by n.n)
     from numbered n where n.n<=lim),'[]'::jsonb),
   (select jsonb_build_object('id',n.id,'at',n.sort_at,'rank',n.rnk,'sort',sort_mode)
      from numbered n where n.n=lim and exists(select 1 from numbered x where x.n>lim))
 into items,next_token;
 return jsonb_build_object('items',items,'next_cursor',next_token,'limit',lim,'sort',sort_mode);
end;$fn$;

create or replace function public.jb_b9_taxonomy_discover(p_query text default null,p_limit int default 30)
returns jsonb language sql stable security definer set search_path=''
as $fn$
 select coalesce(jsonb_agg(row_to_json(q) order by q.kind,q.label),'[]'::jsonb)
 from (
   select distinct t.kind,t.slug,t.label
   from public.b9_taxonomy_terms t join public.b9_article_terms at on at.term_id=t.id
   join public.articles a on a.id=at.article_id
   where a.status='published' and a.deleted_at is null
     and (nullif(btrim(coalesce(p_query,'')),'') is null or t.label ilike ('%'||left(btrim(p_query),80)||'%'))
   order by t.kind,t.label
   limit greatest(1,least(coalesce(p_limit,30),50))
 ) q
$fn$;

create or replace function public.jb_b9_related_news(p_article_id uuid,p_limit int default 5)
returns jsonb language sql stable security definer set search_path=''
as $fn$
with original as (
 select id,category,district,published_at from public.articles
 where id=p_article_id and status='published' and deleted_at is null
), related as (
 select a.id,a.title,a.category,a.location,a.published_at,
   (case when a.category=o.category then 3 else 0 end
   +case when a.district=o.district then 2 else 0 end
   +3*(select count(*) from public.b9_article_terms x
             join public.b9_article_terms y on y.term_id=x.term_id
              where x.article_id=o.id and y.article_id=a.id)) as score
 from original o join public.articles a on a.id<>o.id
 where a.status='published' and a.deleted_at is null
 order by score desc,a.published_at desc,a.id desc
 limit greatest(3,least(coalesce(p_limit,5),5))
) select coalesce(jsonb_agg(jsonb_build_object(
   'id',id,'title',title,'category',category,'location',location,
   'permanent_url','article.html?id='||id::text,'score',score) order by score desc,published_at desc,id desc),'[]'::jsonb) from related
$fn$;

create or replace function public.jb_b9_reporter_discovery(p_query text default null,p_limit int default 30)
returns jsonb language sql stable security definer set search_path=''
as $fn$
select coalesce(jsonb_agg(jsonb_build_object('display_name',x.display_name,'public_articles',x.stories) order by x.display_name),'[]'::jsonb)
from (
select r.name as display_name,count(a.id)::int as stories
from public.reporters r
join public.team_accounts ta on ta.reporter_id=r.id and ta.status in ('active','departed')
join public.articles a on lower(a.reporter_name)=lower(r.name)
 and a.status='published' and a.deleted_at is null
where r.public_name_enabled is true
 and (nullif(btrim(coalesce(p_query,'')),'') is null or r.name ilike ('%'||left(btrim(p_query),80)||'%'))
group by r.id,r.name
order by r.name
limit greatest(1,least(coalesce(p_limit,30),50))
) x
$fn$;

create or replace function public.jb_b9_public_metrics(p_article_id uuid)
returns jsonb language plpgsql stable security definer set search_path=''
as $fn$
declare
 global_views boolean;global_shares boolean;views_enabled boolean;shares_enabled boolean;
 v_override bigint;raw_views bigint;raw_shares bigint;
begin
 if p_article_id is null or not exists(select 1 from public.articles a
   where a.id=p_article_id and a.status='published' and a.deleted_at is null) then return null;end if;
 select public_views_default,public_shares_default into global_views,global_shares
  from public.b9_metric_global_settings where id=true;
 select coalesce((select s.public_views_enabled from public.article_public_view_settings s
                 where s.article_id=p_article_id),coalesce(global_views,false)),
        coalesce((select s.public_shares_enabled from public.b9_article_share_settings s
                 where s.article_id=p_article_id),coalesce(global_shares,false)),
        (select s.display_override from public.article_public_view_settings s where s.article_id=p_article_id)
 into views_enabled,shares_enabled,v_override;
 select count(*) filter(where event_type='view'),count(*) filter(where event_type='share')
 into raw_views,raw_shares from public.analytics_events where article_id=p_article_id;
 -- Public sees display only if toggle enabled; NEVER raw counts otherwise.
 return jsonb_build_object('article_id',p_article_id,
   'views_enabled',views_enabled,'shares_enabled',shares_enabled,
   'views',case when views_enabled then coalesce(v_override,raw_views) else null end,
   'shares',case when shares_enabled then raw_shares else null end);
end;$fn$;

create or replace function public.jb_b9_owner_analytics(
 p_from timestamptz,p_to timestamptz,p_sort text default 'views',p_limit int default 50
) returns jsonb language plpgsql stable security definer set search_path=''
as $fn$
declare v_summary jsonb;v_articles jsonb;
begin
 if not private.current_owner_aal2() then raise exception 'B9_OWNER_AAL2_REQUIRED';end if;
 if p_from is null or p_to is null or p_to<=p_from or p_to-p_from>interval '3650 days'
 then raise exception 'B9_INVALID_ANALYTICS_WINDOW';end if;
 if coalesce(p_sort,'') not in ('views','shares','latest') then raise exception 'B9_INVALID_ANALYTICS_SORT';end if;
 select jsonb_build_object('views',count(*) filter(where e.event_type='view'),
       'shares',count(*) filter(where e.event_type='share'),
       'total',count(*),'from',p_from,'to',p_to,'timezone','Asia/Kolkata')
 into v_summary
 from public.analytics_events e where e.created_at>=p_from and e.created_at<p_to;
 with totals as(
  select a.id,a.title,a.published_at,
     count(e.id) filter(where e.event_type='view') as views,
     count(e.id) filter(where e.event_type='share') as shares
  from public.articles a left join public.analytics_events e
    on e.article_id=a.id and e.created_at>=p_from and e.created_at<p_to
  group by a.id,a.title,a.published_at
 ), ranked as (
  select * from totals t order by
    case when p_sort='views' then t.views end desc nulls last,
    case when p_sort='shares' then t.shares end desc nulls last,
    t.published_at desc nulls last,t.id desc
  limit greatest(1,least(coalesce(p_limit,50),100))
 )
 select coalesce(jsonb_agg(jsonb_build_object('id',id,'title',title,'views',views,
  'shares',shares,'published_at',published_at)),'[]'::jsonb) into v_articles from ranked;
 return jsonb_build_object('summary',v_summary,'articles',v_articles);
end;$fn$;

create or replace function public.jb_b9_owner_metric_settings(
 p_global boolean,p_article_id uuid default null,p_views boolean default null,p_shares boolean default null,
 p_display_override bigint default null
) returns jsonb language plpgsql security definer set search_path=''
as $fn$
declare v_actor uuid:=auth.uid();v_before jsonb;v_after jsonb;
begin
 if not private.current_owner_aal2() then raise exception 'B9_OWNER_AAL2_REQUIRED';end if;
 if p_display_override is not null and (p_display_override<0 or not p_global)
 then raise exception 'B9_INVALID_OVERRIDE';end if;
 if p_global then
  if p_article_id is not null then raise exception 'B9_GLOBAL_ARTICLE_CONFLICT';end if;
  select to_jsonb(x) into v_before from public.b9_metric_global_settings x where id=true;
  insert into public.b9_metric_global_settings(id,public_views_default,public_shares_default,updated_by)
  values(true,coalesce(p_views,false),coalesce(p_shares,false),v_actor)
  on conflict(id) do update set public_views_default=excluded.public_views_default,
       public_shares_default=excluded.public_shares_default,updated_by=v_actor,updated_at=now();
  select to_jsonb(x) into v_after from public.b9_metric_global_settings x where id=true;
 else
  if p_article_id is null or not exists(select 1 from public.articles where id=p_article_id)
  then raise exception 'B9_ARTICLE_NOT_FOUND';end if;
  select jsonb_build_object('view',to_jsonb(v),'share',to_jsonb(s)) into v_before
    from (select 1) z
    left join public.article_public_view_settings v on v.article_id=p_article_id
    left join public.b9_article_share_settings s on s.article_id=p_article_id;
  -- Reuse the canonical Phase4 B2 view controls; do not invent a new view override authority.
  perform public.jb_records_set_public_views_internal(v_actor,p_article_id,coalesce(p_views,false),p_display_override);
  insert into public.b9_article_share_settings(article_id,public_shares_enabled,updated_by)
   values(p_article_id,coalesce(p_shares,false),v_actor)
   on conflict(article_id) do update set public_shares_enabled=excluded.public_shares_enabled,
         updated_by=v_actor,updated_at=now();
  select jsonb_build_object('view',to_jsonb(v),'share',to_jsonb(s)) into v_after
    from (select 1) z
    left join public.article_public_view_settings v on v.article_id=p_article_id
    left join public.b9_article_share_settings s on s.article_id=p_article_id;
 end if;
 insert into public.audit_logs(actor_user_id,action,record_type,record_id,metadata)
 values(v_actor,'b9_metric_display_control',
  case when p_global then 'b9_global_metrics' else 'article' end,
  case when p_global then 'global' else p_article_id::text end,
  jsonb_build_object('before',v_before,'after',v_after));
 return jsonb_build_object('saved',true,'global',p_global,'article_id',p_article_id);
end;$fn$;

create or replace function public.jb_b9_owner_assign_term(
 p_article uuid,p_kind text,p_slug text,p_label text,p_action text default 'add'
) returns jsonb language plpgsql security definer set search_path=''
as $fn$
declare actor uuid:=auth.uid();tid bigint;
begin
 if not private.current_owner_aal2() then raise exception 'B9_OWNER_AAL2_REQUIRED';end if;
 if p_article is null or not exists(select 1 from public.articles where id=p_article) then raise exception 'B9_ARTICLE_NOT_FOUND';end if;
 if p_kind not in ('topic','tag') or p_slug !~ '^[a-z0-9][a-z0-9-]{0,79}$'
 or length(btrim(coalesce(p_label,''))) not between 1 and 120 
 or p_action not in ('add','remove') then raise exception 'B9_INVALID_TERM';end if;
 if p_action='add' then
  insert into public.b9_taxonomy_terms(kind,slug,label,created_by)
  values(p_kind,p_slug,btrim(p_label),actor) on conflict(kind,slug) do nothing;
  select id into tid from public.b9_taxonomy_terms where kind=p_kind and slug=p_slug;
  insert into public.b9_article_terms(article_id,term_id,assigned_by)
  values(p_article,tid,actor) on conflict do nothing;
 else
  select id into tid from public.b9_taxonomy_terms where kind=p_kind and slug=p_slug;
  delete from public.b9_article_terms where article_id=p_article and term_id=tid;
 end if;
 insert into public.audit_logs(actor_user_id,action,record_type,record_id,metadata)
 values(actor,'b9_manual_term_'||p_action,'article',p_article::text,
     jsonb_build_object('kind',p_kind,'slug',p_slug,'term_id',tid));
 return jsonb_build_object('article_id',p_article,'kind',p_kind,'slug',p_slug,'action',p_action);
end;$fn$;

