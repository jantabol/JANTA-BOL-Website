create table if not exists public.b9_taxonomy_terms(
 id bigint generated by default as identity primary key,
 kind text not null check(kind in ('topic','tag')),
 slug text not null check(slug ~ '^[a-z0-9][a-z0-9-]{0,79}$'),
 label text not null check(length(btrim(label)) between 1 and 120),
 created_by uuid,
 created_at timestamptz not null default now(),
 unique(kind,slug)
);
create table if not exists public.b9_article_terms(
 article_id uuid not null references public.articles(id) on delete cascade,
 term_id bigint not null references public.b9_taxonomy_terms(id) on delete restrict,
 assigned_by uuid,
 assigned_at timestamptz not null default now(),
 primary key(article_id,term_id)
);
create index if not exists b9_article_terms_term_idx on public.b9_article_terms(term_id,article_id);
create index if not exists b9_taxonomy_label_idx on public.b9_taxonomy_terms(kind,lower(label));
alter table public.b9_taxonomy_terms enable row level security;
alter table public.b9_article_terms enable row level security;
revoke all on public.b9_taxonomy_terms,public.b9_article_terms from public,anon,authenticated;
grant all on public.b9_taxonomy_terms,public.b9_article_terms to service_role;

